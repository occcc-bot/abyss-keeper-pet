export function matchFusionRecipe(
  a: AbyssalSpeciesId,
  b: AbyssalSpeciesId,
): { type: 'tier_up' | 'star_up'; result: AbyssalSpeciesId } | null {
  if (a === 'imp' || b === 'imp') return null;
  if (a === b) {
    return { type: 'star_up', result: a };
  }
  for (const r of FUSION_RECIPES) {
    if (
      (r.ingredients[0] === a && r.ingredients[1] === b) ||
      (r.ingredients[0] === b && r.ingredients[1] === a)
    ) {
      return { type: 'tier_up', result: r.result };
    }
  }
  return null;
}

